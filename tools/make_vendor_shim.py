# -*- coding: utf-8 -*-
"""生成 vendor/hithink-finance.cmd 转发脚本。

为什么需要这一步：
  从资源管理器双击启动时，进程拿到的是「系统持久化的 PATH」。
  node 和 hithink-finance 往往只装在某个带版本的目录里、没进 PATH，
  于是软件找不到行情 CLI，一按扫描就报「找不到 hithink-finance」。

  这个脚本把 node.exe 和 CLI 入口的绝对路径写进 vendor/ 下的转发文件。
  软件查找顺序是 cli_path -> vendor/ -> PATH，所以放好之后双击就能扫。

用法：
  python tools/make_vendor_shim.py                       # 自动查找
  python tools/make_vendor_shim.py --node D:\\n\\node.exe  # 手工指定
  python tools/make_vendor_shim.py --dry-run             # 只看会写什么
"""
import argparse
import glob
import os
import shutil
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
VENDOR = os.path.join(ROOT, 'vendor')
CLI_MAIN = os.path.join('node_modules', '@hithink-tech',
                        'hithink-finance-cli', 'dist', 'cli', 'main.js')


def find_cmd_files():
    """所有能找到的 hithink-finance.cmd。"""
    seen, out = set(), []
    for name in ('hithink-finance.cmd', 'hithink-finance'):
        p = shutil.which(name)
        if p and os.path.isfile(p) and os.path.abspath(p) not in seen:
            seen.add(os.path.abspath(p))
            out.append(os.path.abspath(p))
    # WorkBuddy 自带的 node 运行时不进 PATH，单独找一遍
    for pat in ('~/.workbuddy/binaries/node/versions/*', '~/.nvm/versions/node/*',
                '~/AppData/Roaming/npm', '~/AppData/Local/nvm/*'):
        for d in glob.glob(os.path.expanduser(pat)):
            cand = os.path.join(d, 'hithink-finance.cmd')
            if os.path.isfile(cand) and os.path.abspath(cand) not in seen:
                seen.add(os.path.abspath(cand))
                out.append(os.path.abspath(cand))
    return out


def resolve(cmd_path, node_override=None):
    """从 .cmd 的位置推出 (node.exe, main.js)。"""
    d = os.path.dirname(cmd_path)
    main = os.path.join(d, CLI_MAIN)
    node = node_override or os.path.join(d, 'node.exe')
    return node, main


def write_shim(node, main):
    os.makedirs(VENDOR, exist_ok=True)
    target = os.path.join(VENDOR, 'hithink-finance.cmd')
    body = (
        '@echo off\r\n'
        'rem Generated by tools/make_vendor_shim.py -- do not edit by hand.\r\n'
        'rem Pins node + CLI by absolute path so this works without node on PATH.\r\n'
        f'"{node}" "{main}" %*\r\n'
    )
    with open(target, 'w', encoding='ascii', newline='') as f:
        f.write(body)
    return target


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--node', default=None, help='node.exe 的绝对路径')
    ap.add_argument('--cmd', default=None, help='hithink-finance.cmd 的绝对路径')
    ap.add_argument('--dry-run', action='store_true')
    a = ap.parse_args()

    cands = [a.cmd] if a.cmd else find_cmd_files()
    if not cands:
        print('没找到 hithink-finance。先装它：')
        print('  npm i -g @hithink-tech/hithink-finance-cli')
        print('然后用 --cmd 指给我，或者把 CLI 放进 vendor/。')
        return 1

    chosen = None
    for c in cands:
        node, mainjs = resolve(c, a.node)
        ok_node = os.path.isfile(node) or bool(a.node)
        ok_main = os.path.isfile(mainjs)
        print(f'候选 : {c}')
        print(f'  node   {node}  {"OK" if ok_node else "缺失"}')
        print(f'  main   {mainjs}  {"OK" if ok_main else "缺失"}')
        if ok_node and ok_main:
            chosen = (node, mainjs)
            break

    if not chosen:
        print('\n没有一组路径同时存在。用 --node 手工指定 node.exe。')
        return 2

    node, mainjs = chosen
    # 跑一次验证再落地
    try:
        r = subprocess.run([node, mainjs, '--version'], capture_output=True,
                           text=True, encoding='utf-8', errors='replace', timeout=60)
        ver = (r.stdout or r.stderr or '').strip()
        print(f'\n试跑 : rc={r.returncode} 版本={ver}')
        if r.returncode != 0:
            print('CLI 试跑失败，先解决它再生成转发脚本。')
            return 3
    except Exception as e:
        print(f'\n试跑异常：{e}')
        return 3

    if a.dry_run:
        print(f'\n[dry-run] 会写入 {os.path.join(VENDOR, "hithink-finance.cmd")}')
        return 0

    p = write_shim(node, mainjs)
    print(f'\n已写入 {p}')
    print('现在双击快捷方式即可扫描，不依赖 PATH。')
    return 0


if __name__ == '__main__':
    sys.exit(main())
